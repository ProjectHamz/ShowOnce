// review.js — optional side tool using a Gemini managed agent (Antigravity, built on Gemini 4 Hydrogen).
// Not used by the server, the pages, or eval.js. The agent gets copies of README.md and any saved
// runs/run-*.json as text, works in its own Google-hosted sandbox, and returns review notes.
// It never edits project files; its only output is agent-notes/notes.md.
// Usage: npm run review   (uses GEMINI_API_KEY from .env)
import { GoogleGenAI } from "@google/genai";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(ROOT, "agent-notes");
const AGENT = process.env.REVIEW_AGENT || "antigravity-preview-09-2026";

if (!process.env.GEMINI_API_KEY) { console.error("Set GEMINI_API_KEY in .env first."); process.exit(1); }
const client = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY, httpOptions: { apiVersion: "v1beta" } });

function gatherInputs() {
  const parts = [`=== README.md ===\n${fs.readFileSync(path.join(ROOT, "README.md"), "utf8")}`];
  const runsDir = path.join(ROOT, "runs");
  const runs = fs.existsSync(runsDir) ? fs.readdirSync(runsDir).filter((f) => /^run-.*\.json$/.test(f)).sort() : [];
  for (const f of runs) parts.push(`=== runs/${f} ===\n${fs.readFileSync(path.join(runsDir, f), "utf8")}`);
  return { text: parts.join("\n\n"), runCount: runs.length };
}

async function main() {
  const { text, runCount } = gatherInputs();
  const task = `You write review notes for Show Once, a hackathon project that watches someone do a hands-on procedure
on camera and calls out skipped, swapped, or extra steps. Below are its README and ${runCount} saved run file(s)
(card = the secret error the player was told to make; events = what the system flagged).

Write markdown with exactly two sections:
## README
3 to 6 concrete suggestions to make the README clearer, each quoting the line it refers to.
## Runs
${runCount ? "How many runs per card type and how many the system flagged correctly. Compute the counts with code in your sandbox; do not estimate." : 'Write the single line "No runs saved yet."'}

Describe the steps and the system only, never the people who played. Reply with the markdown only.

${text}`;

  console.log(`[notes] asking managed agent ${AGENT} (README + ${runCount} run file(s))...`);
  const t0 = Date.now();
  const result = await client.interactions.create(
    { agent: AGENT, input: task, environment: "remote" },
    { timeout: 300_000 },
  );
  const notes = String(result.output_text || "").trim();
  if (!notes) throw new Error("the agent returned no text");

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const header = `<!-- Generated by ${AGENT} (Gemini managed agent) via npm run review; interaction ${result.id || "?"}, ${Math.round((Date.now() - t0) / 1000)} s -->\n\n`;
  fs.writeFileSync(path.join(OUT_DIR, "notes.md"), header + notes + "\n");
  console.log(`[notes] saved agent-notes/notes.md in ${Math.round((Date.now() - t0) / 1000)} s`);
}

main().catch((e) => { console.error("[notes] failed:", e.message); process.exitCode = 1; });
